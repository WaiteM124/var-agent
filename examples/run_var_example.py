#!/usr/bin/env python3
"""Worked 1-day VaR example over the synthetic energy book.

No Azure or LLM credentials are required. Re-run from the repo root:

    python examples/run_var_example.py

This writes examples/output/summary.json, examples/output/summary.md, and
examples/output/pnl_distribution.png. Figures committed in this repository
were produced by this script.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt

from risk.controls import LimitConfig, check_limits
from risk.portfolio import aggregate_precomputed_var, load_positions
from risk.var import expected_shortfall, parametric_var, simulate_portfolio_pnl, var_from_pnl

OUT_DIR = Path(__file__).resolve().parent / "output"
N_PATHS = 20_000
SEED = 42
CORRELATION = 0.4
CONFIDENCE = 95


def main() -> None:
    book = load_positions()
    pre95 = aggregate_precomputed_var(book, 95)
    pre99 = aggregate_precomputed_var(book, 99)
    undiversified_95 = float(
        sum(parametric_var(float(r.notional_usd), float(r.volatility_1d), 95) for r in book.itertuples())
    )
    undiversified_99 = float(
        sum(parametric_var(float(r.notional_usd), float(r.volatility_1d), 99) for r in book.itertuples())
    )

    pnl = simulate_portfolio_pnl(book, n_paths=N_PATHS, seed=SEED, correlation=CORRELATION)
    mc_var_95 = var_from_pnl(pnl, 95)
    mc_var_99 = var_from_pnl(pnl, 99)
    mc_es_95 = expected_shortfall(pnl, 95)
    mc_es_99 = expected_shortfall(pnl, 99)
    breaches = check_limits(book, LimitConfig())

    summary = {
        "book": "data/positions.csv",
        "positions": pre95["positions_count"],
        "total_notional_usd": pre95["total_notional_usd"],
        "assumptions": {
            "n_paths": N_PATHS,
            "seed": SEED,
            "correlation": CORRELATION,
            "horizon_days": 1,
            "process": "GBM, zero drift, daily volatility from the book",
            "options": "delta approximation only",
        },
        "precomputed_sum_var_95_usd": pre95["portfolio_var_95_1d_usd"],
        "precomputed_sum_var_99_usd": pre99["portfolio_var_99_1d_usd"],
        "undiversified_parametric_var_95_usd": round(undiversified_95, 2),
        "undiversified_parametric_var_99_usd": round(undiversified_99, 2),
        "monte_carlo_var_95_usd": round(mc_var_95, 2),
        "monte_carlo_var_99_usd": round(mc_var_99, 2),
        "monte_carlo_es_95_usd": round(mc_es_95, 2),
        "monte_carlo_es_99_usd": round(mc_es_99, 2),
        "pnl_mean_usd": round(float(pnl.mean()), 2),
        "pnl_std_usd": round(float(pnl.std()), 2),
        "limit_breaches": [b.to_dict() for b in breaches],
    }

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    def usd(value: float) -> str:
        return f"${value:,.0f}"

    pre95_var = usd(pre95["portfolio_var_95_1d_usd"])
    pre99_var = usd(pre99["portfolio_var_99_1d_usd"])
    lines = [
        "# Worked example output",
        "",
        (
            f"Generated by `examples/run_var_example.py` with seed {SEED}, "
            f"{N_PATHS:,} paths, and constant pairwise correlation {CORRELATION}. "
            "No cloud credentials were used."
        ),
        "",
        "| Measure | 95% | 99% |",
        "|---|---:|---:|",
        f"| Pre-computed book VaR (sum of position columns) | {pre95_var} | {pre99_var} |",
        f"| Undiversified parametric VaR (sum of |N|σz) | {usd(undiversified_95)} | {usd(undiversified_99)} |",
        f"| Monte Carlo portfolio VaR | {usd(mc_var_95)} | {usd(mc_var_99)} |",
        f"| Monte Carlo expected shortfall | {usd(mc_es_95)} | {usd(mc_es_99)} |",
        "",
        (f"Book notional: {usd(pre95['total_notional_usd'])} across {pre95['positions_count']} synthetic positions."),
        "",
        "Default limit breaches:",
        "",
    ]
    md = "\n".join(lines) + "\n"
    for b in breaches:
        md += f"- `{b.code}` — {b.message}\n"
    md += "\n![1-day Monte Carlo P&L distribution](pnl_distribution.png)\n"
    (OUT_DIR / "summary.md").write_text(md, encoding="utf-8")

    fig, ax = plt.subplots(figsize=(10, 5), dpi=150)
    ax.hist(pnl / 1_000_000, bins=60, color="#1f4e79", alpha=0.85, edgecolor="white", linewidth=0.3)
    ax.axvline(0, color="#444444", linewidth=1, linestyle="--")
    ax.axvline(-mc_var_95 / 1_000_000, color="#c0392b", linewidth=2, label=f"95% VaR ({usd(mc_var_95)})")
    ax.axvline(-mc_var_99 / 1_000_000, color="#8e1b12", linewidth=2, linestyle=":", label=f"99% VaR ({usd(mc_var_99)})")
    ax.set_xlabel("1-day portfolio P&L (USD millions)")
    ax.set_ylabel("Number of paths")
    ax.set_title("Seeded Monte Carlo P&L — synthetic energy book (20,000 paths, ρ = 0.4)")
    ax.legend(frameon=False)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "pnl_distribution.png")
    plt.close(fig)

    print(md)
    print(f"Wrote {OUT_DIR / 'summary.json'}")
    print(f"Wrote {OUT_DIR / 'summary.md'}")
    print(f"Wrote {OUT_DIR / 'pnl_distribution.png'}")


if __name__ == "__main__":
    main()
